"""Object-storage abstraction.

Backends:

* ``LocalStorageBackend``  — content-addressed layout under a local root
  (private single-node deployments).  Keys are generated by the platform,
  never derived from user filenames.
* ``S3StorageBackend``     — S3-compatible object storage (AWS S3, MinIO,
  ...) via boto3 (optional dependency, guarded).

Both stream data in chunks; nothing loads unbounded file content into
application memory.
"""

from __future__ import annotations

import asyncio
import contextlib
import os
import uuid
from collections.abc import AsyncIterator
from pathlib import Path
from typing import Protocol

import structlog

from app.core.config import Settings
from app.core.errors import NotFoundError, PathTraversalError, StorageError

logger = structlog.stdlib.get_logger("app.storage")

CHUNK_SIZE = 1024 * 1024


class StorageBackend(Protocol):
    name: str

    async def save(self, key: str, stream: AsyncIterator[bytes], *, expected_size: int) -> int: ...
    async def read(self, key: str) -> AsyncIterator[bytes]: ...
    async def read_bounded(self, key: str, max_bytes: int) -> bytes: ...
    async def delete(self, key: str) -> None: ...
    async def exists(self, key: str) -> bool: ...
    async def probe(self) -> None: ...


class LocalStorageBackend:
    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path_for(self, key: str) -> Path:
        if not key or "\x00" in key or key.startswith("/") or ".." in key.split("/"):
            raise PathTraversalError("invalid storage key")
        candidate = (self.root / key).resolve()
        if candidate != self.root and self.root not in candidate.parents:
            raise PathTraversalError("storage key escapes root")
        return candidate

    async def save(self, key: str, stream: AsyncIterator[bytes], *, expected_size: int) -> int:
        target = self._path_for(key)
        await asyncio.to_thread(
            lambda: target.parent.mkdir(parents=True, exist_ok=True)
        )
        temp_path = target.with_suffix(f".{uuid.uuid4().hex}.part")
        written = 0
        try:
            # Streamed write: consume the async iterator on the event loop and
            # perform blocking writes in threads chunk-by-chunk.
            def _open():
                return open(temp_path, "wb")

            fh = await asyncio.to_thread(_open)
            try:
                async for chunk in stream:
                    written += len(chunk)
                    if written > expected_size:
                        raise StorageError("upload exceeded the declared size")
                    await asyncio.to_thread(fh.write, chunk)
            finally:
                await asyncio.to_thread(fh.close)
            os.replace(temp_path, target)
        except Exception:
            with contextlib.suppress(OSError):
                temp_path.unlink(missing_ok=True)
            raise
        return written

    async def read(self, key: str) -> AsyncIterator[bytes]:
        target = self._path_for(key)
        if not target.is_file():
            raise NotFoundError("object not found")

        def _open():
            return open(target, "rb")

        fh = await asyncio.to_thread(_open)
        try:
            while True:
                chunk = await asyncio.to_thread(fh.read, CHUNK_SIZE)
                if not chunk:
                    break
                yield chunk
        finally:
            await asyncio.to_thread(fh.close)

    async def read_bounded(self, key: str, max_bytes: int) -> bytes:
        buffer = bytearray()
        async for chunk in self.read(key):
            buffer.extend(chunk)
            if len(buffer) > max_bytes:
                raise StorageError(
                    "object exceeds the maximum readable size",
                    details={"max_bytes": max_bytes},
                )
        return bytes(buffer)

    async def delete(self, key: str) -> None:
        target = self._path_for(key)
        await asyncio.to_thread(lambda: target.unlink(missing_ok=True))

    async def exists(self, key: str) -> bool:
        return self._path_for(key).is_file()

    async def probe(self) -> None:
        probe_key = f".probe-{uuid.uuid4().hex}"

        async def _one() -> AsyncIterator[bytes]:
            yield b"probe"

        await self.save(probe_key, _one(), expected_size=8)
        if not await self.exists(probe_key):
            raise StorageError("storage probe failed")
        await self.delete(probe_key)


class S3StorageBackend:
    """S3-compatible storage via boto3 (optional dependency)."""

    name = "s3"

    def __init__(self, client: object, bucket: str) -> None:
        self._client = client
        self.bucket = bucket

    @classmethod
    def from_settings(cls, settings: Settings) -> "S3StorageBackend":
        try:
            import boto3  # type: ignore
        except ImportError as exc:  # pragma: no cover
            raise StorageError(
                "boto3 is required for S3 storage (pip install boto3)"
            ) from exc
        client = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url,
            region_name=settings.s3_region,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=(
                settings.s3_secret_access_key.get_secret_value()
                if settings.s3_secret_access_key
                else None
            ),
        )
        return cls(client, settings.s3_bucket)

    async def save(self, key: str, stream: AsyncIterator[bytes], *, expected_size: int) -> int:
        import io

        buffer = io.BytesIO()
        written = 0
        async for chunk in stream:
            written += len(chunk)
            if written > expected_size:
                raise StorageError("upload exceeded the declared size")
            buffer.write(chunk)
        buffer.seek(0)

        def _put():
            self._client.put_object(Bucket=self.bucket, Key=key, Body=buffer)

        await asyncio.to_thread(_put)
        return written

    async def read(self, key: str) -> AsyncIterator[bytes]:
        def _get():
            return self._client.get_object(Bucket=self.bucket, Key=key)["Body"]

        body = await asyncio.to_thread(_get)

        while True:
            chunk = await asyncio.to_thread(body.read, CHUNK_SIZE)
            if not chunk:
                break
            yield chunk

    async def read_bounded(self, key: str, max_bytes: int) -> bytes:
        buffer = bytearray()
        async for chunk in self.read(key):
            buffer.extend(chunk)
            if len(buffer) > max_bytes:
                raise StorageError("object exceeds the maximum readable size")
        return bytes(buffer)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(
            lambda: self._client.delete_object(Bucket=self.bucket, Key=key)
        )

    async def exists(self, key: str) -> bool:
        def _head() -> bool:
            try:
                self._client.head_object(Bucket=self.bucket, Key=key)
                return True
            except Exception:
                return False

        return await asyncio.to_thread(_head)

    async def probe(self) -> None:
        def _list() -> int:
            return len(self._client.list_objects_v2(Bucket=self.bucket, MaxKeys=1).get("Contents", []))

        await asyncio.to_thread(_list)


def get_storage(settings: Settings) -> StorageBackend:
    if settings.storage_backend == "s3":
        return S3StorageBackend.from_settings(settings)
    return LocalStorageBackend(settings.storage_local_root)


def new_storage_key(user_id) -> str:
    """Opaque, unguessable storage key (never derived from filenames)."""
    return f"files/{uuid.uuid4()}/{uuid.uuid4().hex}"
